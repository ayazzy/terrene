'use client';

import { useState } from 'react';
import {
  Download,
  FileText,
  ArrowUpRight,
  MapPin,
  CircleHelp,
} from 'lucide-react';
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from '@/components/ui/dialog';
import {
  Sheet,
  SheetContent,
  SheetHeader,
  SheetTitle,
  SheetDescription,
} from '@/components/ui/sheet';
import {
  screeningValue,
  type ContextItem,
  type EvidenceRefs,
  type ScreeningAssessment,
} from './screening-context';
import type { SiteWorkspaceState } from './site-workspace-state';
import {
  gapLabel,
  prioritizeFacts,
  prioritizeGaps,
  prioritizeQuestions,
  siteBriefLabel,
  siteBriefValue,
  sitePictureFacts,
} from './site-brief';

type Props = {
  assessment: ScreeningAssessment;
  hasResult: boolean;
  mode: 'overview' | 'evidence';
  context: SiteWorkspaceState['context'];
  onEvidence: () => void;
  onMap?: (key: string) => void;
  mapTargets?: string[];
  site: {
    name: string;
    areaHa?: number;
  };
};

export default function ScreeningContextPanel({
  assessment,
  hasResult,
  mode,
  context,
  onEvidence,
  onMap,
  mapTargets = [],
  site,
}: Props) {
  const [inspected, setInspected] = useState<{
    id: string;
    value: unknown;
  } | null>(null);
  const { run, state, error } = context;
  const result = run?.result;
  const keyFacts = result ? prioritizeFacts(result) : [];
  const pictureFacts = result ? sitePictureFacts(result) : [];
  const importantGaps = result ? prioritizeGaps(result) : [];
  const reviewQuestions = result ? prioritizeQuestions(result) : [];
  const allReviewQuestions = result
    ? prioritizeQuestions(result, result.review_questions.length)
    : [];
  const factCount = result
    ? result.groups.reduce((total, group) => total + group.facts.length, 0)
    : 0;
  const gapCount = result
    ? result.groups.reduce((total, group) => total + group.gaps.length, 0)
    : 0;
  const catalogue = result
    ? [
        ...result.groups.flatMap((group) => [...group.facts, ...group.gaps]),
        ...result.unconnected_capabilities.map((capability) => ({
          id: capability.legacy_variable,
          ...capability,
        })),
        ...result.sources,
        ...result.raw_references,
        ...result.source_features,
        ...result.objects,
        ...result.relationships,
      ]
    : [];

  function references(refs: Partial<EvidenceRefs>) {
    const ids = Object.values(refs).flatMap((values) => values || []);
    return (
      <details>
        <summary>Evidence references · {ids.length}</summary>
        <div className="screening-refs" aria-label="Evidence references">
          {ids.map((id: string) => {
            const record = catalogue.find((item) => item.id === id);
            const source = result?.sources.find((item) => item.id === id);
            return (
              <button
                className="text-btn"
                key={id}
                onClick={() => setInspected({ id, value: record })}
              >
                {source ? `${source.dataset} · ${source.source_version}` : id}
              </button>
            );
          })}
        </div>
      </details>
    );
  }

  function contextItems(label: string, items: ContextItem[]) {
    return (
      <details className="screening-section evidence-context-group">
        <summary>
          <span>{label}</span>
          <small>{items.length} records</small>
        </summary>
        {items.length === 0 && (
          <p>No context generated by these versioned rules.</p>
        )}
        {items.map((item) => (
          <details className="evidence-record" key={item.id}>
            <summary aria-label={`Inspect ${item.label}`}>
              <span>
                <strong>{item.label}</strong>
                <small>{item.text}</small>
              </span>
            </summary>
            <div className="evidence-record-detail">
              {references(item.references)}
            </div>
          </details>
        ))}
      </details>
    );
  }

  const canPrepare =
    hasResult && ['completed', 'partial'].includes(assessment.state);
  const status =
    state === 'checking'
      ? 'Checking saved Screening Context…'
      : state === 'preparing'
        ? 'Preparing Screening Context…'
        : state === 'available'
          ? `Available · saved boundary v${assessment.version}`
          : state === 'absent'
            ? 'No Screening Context prepared for this assessment.'
            : state === 'unsupported'
              ? 'Screening Context is unsupported for this historical assessment.'
              : state === 'unauthorized'
                ? 'Screening Context access requires authentication or permission.'
                : state === 'idle'
                  ? 'Select a saved assessment to inspect its context.'
                  : 'Screening Context could not be loaded.';

  return (
    <section
      className={`screening-context screening-${mode}`}
      aria-label={
        mode === 'overview'
          ? 'Screening Context overview'
          : 'Screening Context evidence'
      }
    >
      <div className="screening-heading">
        <span>
          <FileText size={18} />
          <span>
            <p className="eyebrow">TERRENE EARTH</p>
            <h2>{mode === 'overview' ? 'Site brief' : 'Evidence register'}</h2>
          </span>
        </span>
        <output>{status}</output>
      </div>
      <p className="nature-muted">
        {mode === 'overview'
          ? 'A concise, source-bounded view for human diligence. This context does not score the site or make a team decision.'
          : 'Detailed observations, gaps, source limitations and provenance for the selected immutable assessment.'}
      </p>
      {error && (
        <p role="alert" className="alert">
          {error}
        </p>
      )}
      <div className="screening-actions">
        {state === 'absent' && canPrepare && (
          <button onClick={() => void context.prepare()}>
            Prepare / reuse Screening Context
          </button>
        )}
        {state === 'preparing' && <button disabled>Preparing context…</button>}
        {(state === 'failed' || state === 'unauthorized') && (
          <button className="text-btn" onClick={context.retry}>
            Retry Screening Context
          </button>
        )}
        {result && run && mode === 'evidence' && (
          <button
            onClick={() => void context.exportReport()}
            disabled={context.exporting}
          >
            <Download size={14} />
            {context.exporting
              ? 'Exporting Screening Context…'
              : 'Export Screening Context'}
          </button>
        )}
      </div>
      {state === 'absent' && !canPrepare && (
        <p className="nature-muted">
          A completed or partial assessment with a saved result is required.
        </p>
      )}

      {mode === 'overview' && !result && (
        <>
          <section
            className="site-picture is-basic"
            aria-labelledby="site-picture-basic"
          >
            <p className="context-kind">Site picture</p>
            <h3 id="site-picture-basic">{site.name}</h3>
            <dl className="site-picture-basics">
              <div>
                <dt>Area</dt>
                <dd>
                  {site.areaHa == null
                    ? 'Available after assessment'
                    : `${site.areaHa.toLocaleString('en-GB', { maximumFractionDigits: 2 })} ha`}
                </dd>
              </div>
              <div>
                <dt>Boundary</dt>
                <dd>Version {assessment.version}</dd>
              </div>
              <div>
                <dt>Assessment</dt>
                <dd>{assessment.state.replaceAll('_', ' ')}</dd>
              </div>
            </dl>
          </section>
          <section className="context-preparation-note">
            <h3>Prepare the site brief</h3>
            <p>
              Screening Context adds prioritized mapped evidence, explicit
              unknowns and review questions from this saved assessment.
              Preparing it creates an immutable, reusable run.
            </p>
          </section>
        </>
      )}

      {result && run && mode === 'overview' && (
        <>
          <section
            className="site-picture"
            aria-labelledby="site-picture-heading"
          >
            <p className="context-kind">Site picture</p>
            <h3 id="site-picture-heading">Mapped context at a glance</h3>
            <div className="site-picture-facts">
              {pictureFacts.map((fact) => (
                <div key={fact.id}>
                  <span>{fact.category}</span>
                  <strong>{siteBriefValue(fact)}</strong>
                  <small>{siteBriefLabel(fact, context.map)}</small>
                </div>
              ))}
            </div>
          </section>
          <section
            className="brief-section"
            aria-labelledby="key-evidence-heading"
          >
            <p className="context-kind">What matters first</p>
            <h3 id="key-evidence-heading">Key evidence</h3>
            <div className="brief-rows">
              {keyFacts.map((fact) => {
                const showOnMap =
                  !!fact.mapKey && mapTargets.includes(fact.mapKey);
                return (
                  <button
                    key={fact.id}
                    aria-label={`${showOnMap ? 'Show on map' : 'View evidence'}: ${siteBriefLabel(fact, context.map)}`}
                    onClick={() =>
                      showOnMap ? onMap?.(fact.mapKey!) : onEvidence()
                    }
                  >
                    <span className="brief-row-copy">
                      <span className="brief-row-label">
                        <small>{fact.category}</small>
                        {siteBriefLabel(fact, context.map)}
                      </span>
                      <small>
                        {fact.availability}
                        {fact.known_zero ? ' · known source-bounded zero' : ''}
                      </small>
                    </span>
                    <span className="brief-row-value">
                      <strong>{siteBriefValue(fact)}</strong>
                      <small>
                        {showOnMap ? (
                          <>
                            <MapPin size={12} /> Show on map
                          </>
                        ) : (
                          'View evidence'
                        )}
                      </small>
                    </span>
                  </button>
                );
              })}
            </div>
          </section>
          <section
            className="brief-section important-unknowns"
            aria-labelledby="important-unknowns-heading"
          >
            <p className="context-kind">Evidence to resolve</p>
            <h3 id="important-unknowns-heading">Important unknowns</h3>
            {importantGaps.length ? (
              <div className="unknown-rows">
                {importantGaps.map((gap) => (
                  <button key={gap.id} onClick={onEvidence}>
                    <span>
                      <strong>{gapLabel(gap)}</strong>
                      <small>{gap.reason}</small>
                    </span>
                    <ArrowUpRight size={14} />
                  </button>
                ))}
              </div>
            ) : (
              <p className="nature-muted">
                No explicit priority gaps are recorded. This does not establish
                evidence completeness.
              </p>
            )}
          </section>
          <section
            className="brief-section review-questions"
            aria-labelledby="review-questions-heading"
          >
            <p className="context-kind">
              <CircleHelp size={12} /> Human diligence
            </p>
            <h3 id="review-questions-heading">Review questions</h3>
            {reviewQuestions.length ? (
              <ol>
                {reviewQuestions.map((item) => (
                  <li key={item.id}>{item.text}</li>
                ))}
              </ol>
            ) : (
              <p>
                No questions were generated by these versioned rules; this does
                not establish evidence completeness.
              </p>
            )}
          </section>
          <button className="evidence-summary-link" onClick={onEvidence}>
            <span>
              <strong>Inspect detailed evidence and provenance</strong>
              <small>
                Open every observation, gap, limitation and source reference
              </small>
            </span>
            <ArrowUpRight size={16} />
          </button>
        </>
      )}

      {result && run && mode === 'evidence' && (
        <>
          <section
            className="evidence-register-overview"
            aria-labelledby="evidence-register-overview-heading"
          >
            <p className="context-kind">Evidence index</p>
            <h3 id="evidence-register-overview-heading">
              What this assessment contains
            </h3>
            <dl>
              <div>
                <dt>Earth facts</dt>
                <dd>{factCount}</dd>
              </div>
              <div>
                <dt>Known gaps</dt>
                <dd>{gapCount}</dd>
              </div>
              <div>
                <dt>Sources</dt>
                <dd>{result.sources.length}</dd>
              </div>
            </dl>
          </section>
          <details className="screening-section evidence-run-record">
            <summary>
              <span>Assessment record</span>
              <small>Run, snapshot and boundary identity</small>
            </summary>
            <dl>
              <dt>Module</dt>
              <dd>{result.model_version}</dd>
              <dt>Rules</dt>
              <dd>{result.input_binding_version}</dd>
              <dt>Run</dt>
              <dd>{run.id}</dd>
              <dt>Snapshot</dt>
              <dd>{result.evidence_snapshot_id}</dd>
              <dt>Evidence hash</dt>
              <dd>{result.evidence_content_hash}</dd>
              <dt>Boundary fingerprint</dt>
              <dd>{result.boundary_geometry_fingerprint}</dd>
              <dt>Evidence as of</dt>
              <dd>{result.evidence_as_of}</dd>
            </dl>
          </details>
          {result.groups.map((group) => (
            <details
              className="screening-section evidence-domain"
              key={group.id}
            >
              <summary>
                <span>{group.label}</span>
                <small>
                  {group.facts.length} fact
                  {group.facts.length === 1 ? '' : 's'} · {group.gaps.length}{' '}
                  gap{group.gaps.length === 1 ? '' : 's'}
                </small>
              </summary>
              <h3 className="evidence-subheading">
                Source-bounded Earth facts
              </h3>
              {!group.facts.length && (
                <p>
                  No source-backed observations retained in this group; this is
                  not mapped zero.
                </p>
              )}
              {group.facts.map((fact) => (
                <details className="evidence-record" key={fact.id}>
                  <summary>
                    <span>
                      <strong>{fact.label}</strong>
                      <small>
                        {fact.availability}
                        {fact.known_zero ? ' · known source-bounded zero' : ''}
                      </small>
                    </span>
                    <b>{screeningValue(fact)}</b>
                  </summary>
                  <div className="evidence-record-detail">
                    <p className="nature-muted">{fact.limitations}</p>
                    <details>
                      <summary>Definition, support and provenance</summary>
                      <pre>{JSON.stringify(fact, null, 2)}</pre>
                    </details>
                    {references(fact.references)}
                  </div>
                </details>
              ))}
              <h3 className="evidence-subheading">Evidence gaps</h3>
              {!group.gaps.length && (
                <p>
                  No explicit gaps recorded in this group; evidence completeness
                  is not established.
                </p>
              )}
              {group.gaps.map((gap) => (
                <details className="evidence-record is-gap" key={gap.id}>
                  <summary>
                    <span>
                      <strong>{gapLabel(gap)}</strong>
                      <small>{gap.reason_code.replaceAll('_', ' ')}</small>
                    </span>
                    <b>{gap.state.replaceAll('_', ' ')}</b>
                  </summary>
                  <div className="evidence-record-detail">
                    <p>{gap.reason}</p>
                    {references({
                      gap_ids: [gap.id],
                      source_reference_ids: gap.source_reference_ids,
                      raw_reference_ids: gap.raw_reference_ids,
                    })}
                  </div>
                </details>
              ))}
            </details>
          ))}
          <div className="evidence-supporting-heading">
            <p className="context-kind">Supporting records</p>
            <h3>Review context and provenance</h3>
          </div>
          <details className="screening-section evidence-context-group">
            <summary>
              <span>Registered but unconnected capabilities</span>
              <small>{result.unconnected_capabilities.length} records</small>
            </summary>
            {result.unconnected_capabilities.map((capability) => (
              <details
                className="evidence-record"
                key={capability.legacy_variable}
              >
                <summary
                  aria-label={`Inspect ${capability.legacy_variable.replaceAll('_', ' ')}`}
                >
                  <span>
                    <strong>
                      {capability.legacy_variable.replaceAll('_', ' ')}
                    </strong>
                    <small>{capability.note}</small>
                  </span>
                </summary>
                <div className="evidence-record-detail">
                  {references({
                    capability_ids: [capability.legacy_variable],
                  })}
                </div>
              </details>
            ))}
          </details>
          {contextItems(
            'Mapped-zero qualifications',
            result.mapped_zero_qualifications,
          )}
          {contextItems(
            'Source-semantic context',
            result.cross_source_contexts,
          )}
          {contextItems(
            'Unresolved human-review questions',
            allReviewQuestions,
          )}
          <details className="screening-section evidence-context-group">
            <summary>
              <span>Source and object catalogue</span>
              <small>
                {result.sources.length +
                  result.objects.length +
                  result.relationships.length +
                  result.source_features.length}{' '}
                records
              </small>
            </summary>
            {references({
              source_reference_ids: [
                ...result.sources,
                ...result.objects,
                ...result.relationships,
                ...result.source_features,
              ].map((record) => record.id),
              raw_reference_ids: result.raw_references.map(
                (record) => record.id,
              ),
            })}
          </details>
          <details className="screening-section evidence-context-group">
            <summary>
              <span>Limitations</span>
              <small>{result.limitations.length} records</small>
            </summary>
            <ul>
              {result.limitations.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          </details>
        </>
      )}

      <Dialog
        open={!!context.exportHtml}
        onOpenChange={(open) => {
          if (!open) context.closeExport();
        }}
      >
        <DialogContent className="report-dialog">
          <DialogHeader>
            <DialogTitle>Screening Context export</DialogTitle>
            <DialogDescription>
              Saved calculated context with current team review status labelled
              separately.
            </DialogDescription>
          </DialogHeader>
          <div className="actions">
            <a
              className="download-link"
              href={context.exportUrl}
              download="terrene-screening-context.html"
            >
              Download Screening Context HTML
            </a>
          </div>
          <iframe
            title="Screening Context HTML preview"
            srcDoc={context.exportHtml}
            sandbox=""
          />
        </DialogContent>
      </Dialog>
      {mode === 'evidence' && (
        <Sheet
          open={!!inspected}
          onOpenChange={(open) => {
            if (!open) setInspected(null);
          }}
        >
          <SheetContent className="evidence-sheet screening-inspector">
            <SheetHeader>
              <SheetTitle>Screening evidence reference</SheetTitle>
              <SheetDescription>{inspected?.id}</SheetDescription>
            </SheetHeader>
            <pre>{JSON.stringify(inspected?.value, null, 2)}</pre>
          </SheetContent>
        </Sheet>
      )}
    </section>
  );
}

'use client';

import { useState } from 'react';
import {
  Download,
  FileText,
  ArrowUpRight,
  MapPin,
  CircleHelp,
  ChevronDown,
} from 'lucide-react';
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from '@/components/ui/dialog';
import {
  Sheet,
  SheetContent,
  SheetHeader,
  SheetTitle,
  SheetDescription,
} from '@/components/ui/sheet';
import {
  screeningValue,
  type ContextItem,
  type EvidenceRefs,
  type ScreeningAssessment,
} from './screening-context';
import type { SiteWorkspaceState } from './site-workspace-state';
import {
  formatMappedMeasurement,
  mapFeatureName,
  mapLayerLabel,
  mapLayerStatus,
} from './screening-map-features';
import {
  evidenceAvailabilityLabel,
  evidenceFactLabel,
  evidenceGapReasonLabel,
  evidenceGapStateLabel,
  gapLabel,
  prioritizeFacts,
  prioritizeGaps,
  prioritizeQuestions,
  siteBriefLabel,
  siteBriefValue,
  sitePictureFacts,
} from './site-brief';

type Props = {
  assessment: ScreeningAssessment;
  hasResult: boolean;
  mode: 'overview' | 'evidence';
  context: SiteWorkspaceState['context'];
  mapEvidence: SiteWorkspaceState['mapEvidence'];
  onEvidence: () => void;
  onMap?: (key: string) => void;
  mapTargets?: string[];
  site: {
    name: string;
    areaHa?: number;
  };
};

export default function ScreeningContextPanel({
  assessment,
  hasResult,
  mode,
  context,
  mapEvidence,
  onEvidence,
  onMap,
  mapTargets = [],
  site,
}: Props) {
  const [inspected, setInspected] = useState<{
    id: string;
    value: unknown;
  } | null>(null);
  const { run, state, error } = context;
  const result = run?.result;
  const keyFacts = result ? prioritizeFacts(result) : [];
  const pictureFacts = result ? sitePictureFacts(result) : [];
  const pictureFactIds = new Set(pictureFacts.map((fact) => fact.id));
  const supportingFacts = keyFacts.filter(
    (fact) => !pictureFactIds.has(fact.id),
  );
  const importantGaps = result ? prioritizeGaps(result) : [];
  const reviewQuestions = result ? prioritizeQuestions(result) : [];
  const allReviewQuestions = result
    ? prioritizeQuestions(result, result.review_questions.length)
    : [];
  const factCount = result
    ? result.groups.reduce((total, group) => total + group.facts.length, 0)
    : 0;
  const gapCount = result
    ? result.groups.reduce((total, group) => total + group.gaps.length, 0)
    : 0;
  const catalogue = result
    ? [
        ...result.groups.flatMap((group) => [...group.facts, ...group.gaps]),
        ...result.unconnected_capabilities.map((capability) => ({
          id: capability.legacy_variable,
          ...capability,
        })),
        ...result.sources,
        ...result.raw_references,
        ...result.source_features,
        ...result.objects,
        ...result.relationships,
      ]
    : [];

  function references(refs: Partial<EvidenceRefs>) {
    const ids = Object.values(refs).flatMap((values) => values || []);
    return (
      <details>
        <summary>Source and object references · {ids.length}</summary>
        <div
          className="screening-refs"
          aria-label="Source and object references"
        >
          {ids.map((id: string) => {
            const record = catalogue.find((item) => item.id === id);
            const source = result?.sources.find((item) => item.id === id);
            return (
              <button
                className="text-btn"
                key={id}
                onClick={() => setInspected({ id, value: record })}
              >
                {source ? `${source.dataset} · ${source.source_version}` : id}
              </button>
            );
          })}
        </div>
      </details>
    );
  }

  function contextItems(label: string, items: ContextItem[]) {
    return (
      <details className="screening-section evidence-context-group">
        <summary>
          <span>{label}</span>
          <small>{items.length} records</small>
        </summary>
        {items.length === 0 && (
          <p>No context generated by these versioned rules.</p>
        )}
        {items.map((item) => (
          <details className="evidence-record" key={item.id}>
            <summary aria-label={`Inspect ${item.label}`}>
              <span>
                <strong>{item.label}</strong>
                <small>{item.text}</small>
              </span>
            </summary>
            <div className="evidence-record-detail">
              {references(item.references)}
            </div>
          </details>
        ))}
      </details>
    );
  }

  function mappedLayerEvidence(detail: boolean) {
    if (mapEvidence.state === 'loading')
      return <p>Loading persisted built-world map evidence…</p>;
    if (mapEvidence.state === 'failed')
      return (
        <p role="alert">
          Mapped infrastructure evidence could not be loaded. Missing evidence
          is not treated as zero. {mapEvidence.error}
        </p>
      );
    if (mapEvidence.state === 'unsupported')
      return (
        <p>
          This historical evidence does not support persisted built-world
          objects. Current objects are not substituted.
        </p>
      );
    if (mapEvidence.state === 'unavailable')
      return (
        <p>
          Mapped infrastructure evidence is unavailable for this assessment.
          Missing evidence is not treated as zero.
        </p>
      );
    if (!mapEvidence.features)
      return (
        <p>
          No supported persisted built-world map contract is available for this
          selected assessment.
        </p>
      );
    return (
      <div className="built-world-evidence-list">
        {mapEvidence.features.layers.map((layer) => {
          const features = mapEvidence.features!.features.filter(
            (feature) =>
              feature.properties.layer_id === layer.id &&
              (layer.state === 'available' || layer.state === 'partial'),
          );
          return (
            <article key={layer.id}>
              <div className="built-world-layer-heading">
                <span>
                  <h4>{mapLayerLabel(layer.id)}</h4>
                  <small className={`layer-state state-${layer.state}`}>
                    {mapLayerStatus(layer)}
                  </small>
                </span>
                {features.length > 0 && (
                  <button
                    className="text-btn"
                    onClick={() => mapEvidence.selectObject(features[0].id)}
                  >
                    <MapPin size={13} /> Inspect on map
                  </button>
                )}
              </div>
              <p>{layer.qualification}</p>
              {detail && (
                <>
                  {layer.measurements.map((measurement) => (
                    <p
                      className="built-world-measurement"
                      key={measurement.observation_id}
                    >
                      <strong>
                        {formatMappedMeasurement(
                          measurement.value,
                          measurement.unit,
                        )}
                      </strong>{' '}
                      · {measurement.definition_id.replaceAll('.', ' · ')}
                      {measurement.availability === 'partial'
                        ? ' · partial coverage'
                        : ''}
                    </p>
                  ))}
                  {features.length > 0 && (
                    <div className="built-world-object-links">
                      {features.map((feature, index) => (
                        <button
                          key={feature.id}
                          className="text-btn"
                          aria-pressed={
                            mapEvidence.selectedObjectId === feature.id
                          }
                          onClick={() => mapEvidence.selectObject(feature.id)}
                        >
                          {mapFeatureName(feature)} <small>#{index + 1}</small>
                        </button>
                      ))}
                    </div>
                  )}
                  {!!layer.sources.length && (
                    <p className="nature-muted">
                      Source:{' '}
                      {layer.sources
                        .map(
                          (source) =>
                            `${source.provider} · ${source.dataset} · ${source.release}`,
                        )
                        .join('; ')}
                    </p>
                  )}
                </>
              )}
            </article>
          );
        })}
        <p className="map-source-qualification">
          Generalised mapped geometry supports screening context only. It is not
          surveyed, cadastral, legal or engineering geometry.
        </p>
      </div>
    );
  }

  const canPrepare =
    hasResult && ['completed', 'partial'].includes(assessment.state);
  const status =
    state === 'checking'
      ? 'Checking saved Screening Context…'
      : state === 'preparing'
        ? 'Preparing Screening Context…'
        : state === 'available'
          ? `Available · saved boundary v${assessment.version}`
          : state === 'absent'
            ? 'No Screening Context prepared for this assessment.'
            : state === 'unsupported'
              ? 'Screening Context is unsupported for this historical assessment.'
              : state === 'unauthorized'
                ? 'Screening Context access requires authentication or permission.'
                : state === 'idle'
                  ? 'Select a saved assessment to inspect its context.'
                  : 'Screening Context could not be loaded.';
  const visibleStatus =
    mode === 'evidence' && state === 'available'
      ? `Retained · boundary v${assessment.version}`
      : status;

  return (
    <section
      className={`screening-context screening-${mode}`}
      aria-label={
        mode === 'overview'
          ? 'Screening Context overview'
          : 'Screening Context evidence'
      }
    >
      <div className="screening-heading">
        <span>
          <FileText size={18} />
          <span>
            <p className="eyebrow">
              {mode === 'overview' ? 'SITE DILIGENCE' : 'SITE EVIDENCE'}
            </p>
            <h2>
              {mode === 'overview' ? 'Analyst brief' : 'Assessment evidence'}
            </h2>
          </span>
        </span>
        <output>{visibleStatus}</output>
      </div>
      <p className="nature-muted">
        {mode === 'overview'
          ? 'Evidence tied to retained sources for deciding what to inspect next. This brief does not score the site or make a team decision.'
          : 'Review what the retained sources show, what remains unknown and the audit trail behind each item.'}
      </p>
      {error && (
        <p role="alert" className="alert">
          {error}
        </p>
      )}
      <div className="screening-actions">
        {state === 'absent' && canPrepare && (
          <button onClick={() => void context.prepare()}>
            Prepare / reuse Screening Context
          </button>
        )}
        {state === 'preparing' && <button disabled>Preparing context…</button>}
        {(state === 'failed' || state === 'unauthorized') && (
          <button className="text-btn" onClick={context.retry}>
            Retry Screening Context
          </button>
        )}
        {result && run && mode === 'evidence' && (
          <button
            onClick={() => void context.exportReport()}
            disabled={context.exporting}
          >
            <Download size={14} />
            {context.exporting
              ? 'Preparing evidence record…'
              : 'Download evidence record'}
          </button>
        )}
      </div>
      {state === 'absent' && !canPrepare && (
        <p className="nature-muted">
          A completed or partial assessment with a saved result is required.
        </p>
      )}

      {mode === 'overview' && !result && (
        <>
          <section
            className="site-picture is-basic"
            aria-labelledby="site-picture-basic"
          >
            <p className="context-kind">What we know</p>
            <h3 id="site-picture-basic">{site.name}</h3>
            <dl className="site-picture-basics">
              <div>
                <dt>Area</dt>
                <dd>
                  {site.areaHa == null
                    ? 'Available after assessment'
                    : `${site.areaHa.toLocaleString('en-GB', { maximumFractionDigits: 2 })} ha`}
                </dd>
              </div>
              <div>
                <dt>Boundary</dt>
                <dd>Version {assessment.version}</dd>
              </div>
              <div>
                <dt>Assessment</dt>
                <dd>{assessment.state.replaceAll('_', ' ')}</dd>
              </div>
            </dl>
          </section>
          <section className="context-preparation-note">
            <h3>Prepare the site brief</h3>
            <p>
              Screening Context adds prioritized mapped evidence, explicit
              unknowns and review questions from this saved assessment.
              Preparing it creates an immutable, reusable run.
            </p>
          </section>
        </>
      )}

      {result && run && mode === 'overview' && (
        <>
          <section
            className="site-picture"
            aria-labelledby="site-picture-heading"
          >
            <p className="context-kind">What we know</p>
            <h3 id="site-picture-heading">Current evidence picture</h3>
            <div className="site-picture-facts">
              {pictureFacts.map((fact) => (
                <div key={fact.id}>
                  <span>{fact.category}</span>
                  <strong>{siteBriefValue(fact)}</strong>
                  <small>{siteBriefLabel(fact, mapEvidence.features)}</small>
                </div>
              ))}
            </div>
          </section>
          <section
            className="brief-section important-unknowns"
            aria-labelledby="important-unknowns-heading"
          >
            <p className="context-kind">What needs attention</p>
            <h3 id="important-unknowns-heading">Evidence gaps</h3>
            {importantGaps.length ? (
              <div className="unknown-rows">
                {importantGaps.map((gap) => (
                  <button key={gap.id} onClick={onEvidence}>
                    <span>
                      <strong>{gapLabel(gap)}</strong>
                      <small>{gap.reason}</small>
                    </span>
                    <ArrowUpRight size={14} />
                  </button>
                ))}
              </div>
            ) : (
              <p className="nature-muted">
                No explicit priority gaps are recorded. This does not establish
                evidence completeness.
              </p>
            )}
          </section>
          <section
            className="brief-section review-questions"
            aria-labelledby="review-questions-heading"
          >
            <p className="context-kind">
              <CircleHelp size={12} /> What to verify next
            </p>
            <h3 id="review-questions-heading">Analyst questions</h3>
            {reviewQuestions.length ? (
              <ol>
                {reviewQuestions.map((item) => (
                  <li key={item.id}>{item.text}</li>
                ))}
              </ol>
            ) : (
              <p>
                No questions were generated by these versioned rules; this does
                not establish evidence completeness.
              </p>
            )}
          </section>
          {supportingFacts.length > 0 && (
            <details className="diligence-disclosure supporting-evidence">
              <summary>
                <span>
                  <strong>Additional retained evidence</strong>
                  <small>
                    Supporting signals not repeated in the headline view
                  </small>
                </span>
                <span className="diligence-disclosure-state">
                  <small>{supportingFacts.length} signals</small>
                  <ChevronDown size={15} aria-hidden="true" />
                </span>
              </summary>
              <div className="diligence-disclosure-body brief-rows">
                {supportingFacts.map((fact) => {
                  const showOnMap =
                    !!fact.mapKey && mapTargets.includes(fact.mapKey);
                  return (
                    <button
                      key={fact.id}
                      aria-label={`${showOnMap ? 'Show on map' : 'View evidence'}: ${siteBriefLabel(fact, mapEvidence.features)}`}
                      onClick={() =>
                        showOnMap ? onMap?.(fact.mapKey!) : onEvidence()
                      }
                    >
                      <span className="brief-row-copy">
                        <span className="brief-row-label">
                          <small>{fact.category}</small>
                          {siteBriefLabel(fact, mapEvidence.features)}
                        </span>
                        <small>{evidenceAvailabilityLabel(fact)}</small>
                      </span>
                      <span className="brief-row-value">
                        <strong>{siteBriefValue(fact)}</strong>
                        <small>
                          {showOnMap ? (
                            <>
                              <MapPin size={12} /> Show on map
                            </>
                          ) : (
                            'View evidence'
                          )}
                        </small>
                      </span>
                    </button>
                  );
                })}
              </div>
            </details>
          )}
          <details className="diligence-disclosure context-built-world-summary">
            <summary>
              <span>
                <strong>Mapped infrastructure context</strong>
                <small>
                  Retained objects, coverage and source qualifications
                </small>
              </span>
              <span className="diligence-disclosure-state">
                <small>
                  {mapEvidence.features
                    ? `${mapEvidence.features.layers.length} layers`
                    : 'View detail'}
                </small>
                <ChevronDown size={15} aria-hidden="true" />
              </span>
            </summary>
            <div className="diligence-disclosure-body">
              {mappedLayerEvidence(false)}
            </div>
          </details>
          <button className="evidence-summary-link" onClick={onEvidence}>
            <span>
              <strong>Open full evidence record</strong>
              <small>
                Every observation, gap, limitation and source reference
              </small>
            </span>
            <ArrowUpRight size={16} />
          </button>
        </>
      )}

      {result && run && mode === 'evidence' && (
        <>
          <section
            className="evidence-register-overview"
            aria-labelledby="evidence-register-overview-heading"
          >
            <p className="context-kind">Coverage summary</p>
            <h3 id="evidence-register-overview-heading">
              Evidence available for review
            </h3>
            <dl>
              <div>
                <dt>Retained observations</dt>
                <dd>{factCount}</dd>
              </div>
              <div>
                <dt>Known gaps</dt>
                <dd>{gapCount}</dd>
              </div>
              <div>
                <dt>Source records</dt>
                <dd>{result.sources.length}</dd>
              </div>
            </dl>
          </section>
          <details className="screening-section evidence-run-record">
            <summary>
              <span>Technical record</span>
              <small>Run, snapshot and boundary identifiers</small>
            </summary>
            <dl>
              <dt>Module</dt>
              <dd>{result.model_version}</dd>
              <dt>Rules</dt>
              <dd>{result.input_binding_version}</dd>
              <dt>Run</dt>
              <dd>{run.id}</dd>
              <dt>Snapshot</dt>
              <dd>{result.evidence_snapshot_id}</dd>
              <dt>Evidence hash</dt>
              <dd>{result.evidence_content_hash}</dd>
              <dt>Boundary fingerprint</dt>
              <dd>{result.boundary_geometry_fingerprint}</dd>
              <dt>Evidence as of</dt>
              <dd>{result.evidence_as_of}</dd>
            </dl>
          </details>
          {result.groups.map((group) => (
            <details
              className="screening-section evidence-domain"
              key={group.id}
            >
              <summary>
                <span>{group.label}</span>
                <small>
                  {group.facts.length} observation
                  {group.facts.length === 1 ? '' : 's'} · {group.gaps.length}{' '}
                  gap{group.gaps.length === 1 ? '' : 's'}
                </small>
              </summary>
              <h3 className="evidence-subheading">What the sources show</h3>
              {!group.facts.length && (
                <p>
                  No observations are retained in this group. This does not
                  establish mapped absence.
                </p>
              )}
              {group.facts.map((fact) => (
                <details className="evidence-record" key={fact.id}>
                  <summary>
                    <span>
                      <strong>
                        {evidenceFactLabel(fact, mapEvidence.features)}
                      </strong>
                      <small>{evidenceAvailabilityLabel(fact)}</small>
                    </span>
                    <b>{screeningValue(fact)}</b>
                  </summary>
                  <div className="evidence-record-detail">
                    <p className="nature-muted">{fact.limitations}</p>
                    <details className="technical-evidence-record">
                      <summary>Technical definition and support</summary>
                      <pre>{JSON.stringify(fact, null, 2)}</pre>
                    </details>
                    {references(fact.references)}
                    {fact.references.object_ids.some((id) =>
                      mapEvidence.features?.features.some(
                        (feature) => feature.id === id,
                      ),
                    ) && (
                      <button
                        className="text-btn"
                        onClick={() =>
                          mapEvidence.selectObject(
                            fact.references.object_ids.find((id) =>
                              mapEvidence.features?.features.some(
                                (feature) => feature.id === id,
                              ),
                            )!,
                          )
                        }
                      >
                        <MapPin size={13} /> Show supporting mapped object
                      </button>
                    )}
                  </div>
                </details>
              ))}
              <h3 className="evidence-subheading">What is not established</h3>
              {!group.gaps.length && (
                <p>
                  No explicit gaps are recorded in this group. This does not
                  establish evidence completeness.
                </p>
              )}
              {group.gaps.map((gap) => (
                <details className="evidence-record is-gap" key={gap.id}>
                  <summary>
                    <span>
                      <strong>{gapLabel(gap)}</strong>
                      <small>{evidenceGapReasonLabel(gap)}</small>
                    </span>
                    <b>{evidenceGapStateLabel(gap)}</b>
                  </summary>
                  <div className="evidence-record-detail">
                    <p>{gap.reason}</p>
                    <details className="technical-evidence-record">
                      <summary>Technical gap record</summary>
                      <pre>{JSON.stringify(gap, null, 2)}</pre>
                    </details>
                    {references({
                      gap_ids: [gap.id],
                      source_reference_ids: gap.source_reference_ids,
                      raw_reference_ids: gap.raw_reference_ids,
                    })}
                  </div>
                </details>
              ))}
            </details>
          ))}
          <details className="screening-section">
            <summary>Mapped infrastructure evidence</summary>
            {mappedLayerEvidence(true)}
          </details>
          <div className="evidence-supporting-heading">
            <p className="context-kind">Audit trail</p>
            <h3>Source context and technical records</h3>
          </div>
          <details className="screening-section evidence-context-group">
            <summary>
              <span>Available data not used here</span>
              <small>{result.unconnected_capabilities.length} records</small>
            </summary>
            {result.unconnected_capabilities.map((capability) => (
              <details
                className="evidence-record"
                key={capability.legacy_variable}
              >
                <summary
                  aria-label={`Inspect ${capability.legacy_variable.replaceAll('_', ' ')}`}
                >
                  <span>
                    <strong>
                      {capability.legacy_variable.replaceAll('_', ' ')}
                    </strong>
                    <small>{capability.note}</small>
                  </span>
                </summary>
                <div className="evidence-record-detail">
                  {references({
                    capability_ids: [capability.legacy_variable],
                  })}
                </div>
              </details>
            ))}
          </details>
          {contextItems(
            'Confirmed mapped absences',
            result.mapped_zero_qualifications,
          )}
          {contextItems(
            'How sources should be compared',
            result.cross_source_contexts,
          )}
          {contextItems('Questions for analyst review', allReviewQuestions)}
          <details className="screening-section evidence-context-group">
            <summary>
              <span>Source and mapped-object index</span>
              <small>
                {result.sources.length +
                  result.objects.length +
                  result.relationships.length +
                  result.source_features.length}{' '}
                records
              </small>
            </summary>
            {references({
              source_reference_ids: [
                ...result.sources,
                ...result.objects,
                ...result.relationships,
                ...result.source_features,
              ].map((record) => record.id),
              raw_reference_ids: result.raw_references.map(
                (record) => record.id,
              ),
            })}
          </details>
          <details className="screening-section evidence-context-group">
            <summary>
              <span>Limitations</span>
              <small>{result.limitations.length} records</small>
            </summary>
            <ul>
              {result.limitations.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          </details>
        </>
      )}

      <Dialog
        open={!!context.exportHtml}
        onOpenChange={(open) => {
          if (!open) context.closeExport();
        }}
      >
        <DialogContent className="report-dialog">
          <DialogHeader>
            <DialogTitle>Evidence record export</DialogTitle>
            <DialogDescription>
              Saved evidence context with current team review status labelled
              separately.
            </DialogDescription>
          </DialogHeader>
          <div className="actions">
            <a
              className="download-link"
              href={context.exportUrl}
              download="terrene-screening-context.html"
            >
              Download evidence record HTML
            </a>
          </div>
          <iframe
            title="Evidence record HTML preview"
            srcDoc={context.exportHtml}
            sandbox=""
          />
        </DialogContent>
      </Dialog>
      {mode === 'evidence' && (
        <Sheet
          open={!!inspected}
          onOpenChange={(open) => {
            if (!open) setInspected(null);
          }}
        >
          <SheetContent className="evidence-sheet screening-inspector">
            <SheetHeader>
              <SheetTitle>Source or object reference</SheetTitle>
              <SheetDescription>{inspected?.id}</SheetDescription>
            </SheetHeader>
            <pre>{JSON.stringify(inspected?.value, null, 2)}</pre>
          </SheetContent>
        </Sheet>
      )}
    </section>
  );
}
